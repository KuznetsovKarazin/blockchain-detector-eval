"""V7  Blinded rating form for an independent second reading of the SolidiFI templates.

The form shows each of the 44 templates (study V1) as code, with the weakness class
SolidiFI assigns to it, in a shuffled order and under neutral item ids. It does not
show the first reading, the compiler check, any tool result or the template id.
Raters answer three separate questions per item:

  Q1 operation  - does the code contain the operation the weakness depends on?
  Q2 weakness   - does the code exhibit the weakness as defined (yes / limited / no)?
  Q3 exploit    - is there a plausible attack path with a concrete harm?

Outputs (results/contracts/v7_rater_form/):
  rater_form.xlsx  - the file sent to raters (instructions, definitions, items)
  key.csv          - item id -> template id (kept by the authors, not sent)

    python scripts/v7_rater_form.py
"""
from __future__ import annotations

import random
from pathlib import Path

import pandas as pd
from openpyxl import Workbook
from openpyxl.styles import Alignment, Font, PatternFill
from openpyxl.worksheet.datavalidation import DataValidation

AUDIT = Path("results/contracts/v1_20261030_181838/template_audit.csv")
BUGS = Path("data/raw/SolidiFI/bugs")
OUT = Path("results/contracts/v7_rater_form")
SEED = 20261103

CLASSES = {
    "Re-entrancy": ("Reentrancy (SWC-107)",
                    "An external call lets the callee re-enter the calling contract before the caller has "
                    "finished updating its state, so that the re-entered code runs on stale state."),
    "Unhandled-Exceptions": ("Unchecked call return value (SWC-104)",
                             "The return value of a low-level call (call, send, delegatecall, ...) is not "
                             "checked, so a failed call goes unnoticed and execution continues as if it had succeeded."),
    "Overflow-Underflow": ("Integer overflow / underflow (SWC-101)",
                           "An arithmetic operation can wrap around (Solidity 0.4/0.5 has no built-in checks) "
                           "and the wrapped value is used, e.g. stored, compared, returned or sent."),
    "Timestamp-Dependency": ("Block timestamp dependence (SWC-116)",
                             "Control flow or a value that matters (payout, winner, deadline) depends on "
                             "block.timestamp (now) in a way that a block producer can influence to their advantage."),
    "tx.origin": ("Authorisation through tx.origin (SWC-115)",
                  "tx.origin is used to decide whether the caller is authorised, so a contract called by the "
                  "authorised user can act on the user's behalf."),
    "TOD": ("Transaction-order dependence (SWC-114)",
            "The outcome of a transaction depends on the order in which pending transactions are mined, "
            "and someone who sees a pending transaction can profit by getting theirs mined first."),
    "Unchecked-Send": ("Unprotected Ether transfer (SWC-105)",
                       "Ether can be sent out of the contract by a caller who should not be able to trigger "
                       "the transfer (missing or insufficient access control)."),
}

INSTRUCTIONS = [
    ("Purpose", "You are asked for an independent expert reading of 44 short Solidity code templates. "
     "A benchmark (SolidiFI) injects each template into real contracts and labels the result as vulnerable "
     "to the class shown next to the template. We want to know, for each template, whether the code "
     "actually carries that weakness. Your answers are compared with those of other readers; there are no "
     "trick items and no expected distribution of answers."),
    ("Setting", "Read each template as a fragment of an otherwise ordinary contract compiled with Solidity "
     "0.5.x (no built-in overflow checks). Variable and function names are generated by the benchmark and "
     "carry no meaning. Do not assume extra protection that is not in the code (modifiers, require "
     "statements elsewhere), and do not assume extra harm that is not in the code either."),
    ("Q1 Operation", "Does the code contain the operation that the weakness of the shown class depends on? "
     "Examples: an external call for reentrancy or unchecked return value; an arithmetic operation for "
     "overflow; a read of block.timestamp/now; a read of tx.origin; an Ether transfer. Answer yes / no / unsure."),
    ("Q2 Weakness", "Does the code exhibit the weakness as defined on the 'Classes' sheet? "
     "yes = the defining condition is present; limited = present only under restrictive conditions that "
     "you name in the comment (for example a gas stipend, a value range); no = the defining condition is "
     "absent; unsure = you cannot decide from the code. If Q1 is no, Q2 is normally no."),
    ("Q3 Exploit", "Assuming the template sits in a deployed contract with ordinary surrounding code, is there "
     "a plausible attack path that leads to a concrete harm (loss or theft of funds, wrong balances or "
     "state, denial of service, unfair advantage)? yes / no / unclear. Q3 can be no even when Q2 is yes, "
     "for example when the weakness exists but nothing of value depends on it."),
    ("Confidence and comment", "Give your confidence (1 = low, 2 = medium, 3 = high) and, whenever you answer "
     "limited, no, unsure or unclear, one sentence with the reason."),
    ("Rules", "Work alone and do not discuss items with other readers until everyone has returned the form. "
     "You may read documentation and you may compile or execute the code yourself. Please do not use "
     "automated vulnerability analysers or AI assistants: the study needs a human judgement to compare "
     "with tool output. Expected time: 1.5 to 2.5 hours."),
    ("Return", "Fill in the yellow columns on the 'Items' sheet, write your initials in cell B2 of that sheet, "
     "and return the file unchanged otherwise."),
]


def main() -> None:
    a = pd.read_csv(AUDIT)
    rng = random.Random(SEED)
    order = list(range(len(a)))
    rng.shuffle(order)
    OUT.mkdir(parents=True, exist_ok=True)
    key = []
    wb = Workbook()
    ws = wb.active
    ws.title = "Instructions"
    ws.column_dimensions["A"].width = 24
    ws.column_dimensions["B"].width = 110
    ws["A1"] = "Independent reading of SolidiFI templates"
    ws["A1"].font = Font(bold=True, size=14)
    for i, (h, t) in enumerate(INSTRUCTIONS, start=3):
        ws.cell(i, 1, h).font = Font(bold=True)
        ws.cell(i, 2, t).alignment = Alignment(wrap_text=True, vertical="top")
        ws.cell(i, 1).alignment = Alignment(vertical="top")

    wc = wb.create_sheet("Classes")
    for col, w in zip("ABC", (22, 38, 100)):
        wc.column_dimensions[col].width = w
    wc.append(["Benchmark label", "Weakness", "Definition used in this study"])
    for c in wc[1]:
        c.font = Font(bold=True)
    for k, (name, d) in CLASSES.items():
        wc.append([k, name, d])
        wc.cell(wc.max_row, 3).alignment = Alignment(wrap_text=True, vertical="top")

    wi = wb.create_sheet("Items")
    wi["A2"], wi["A1"] = "Rater initials:", "Fill in the yellow columns. Definitions: sheet 'Classes'."
    wi["A1"].font = Font(italic=True)
    hdr = ["Item", "Benchmark label", "Weakness", "Code", "Q1 operation", "Q2 weakness", "Q3 exploit",
           "Confidence (1-3)", "Comment"]
    wi.append([])
    wi.append(hdr)
    H = 4
    for c in wi[H]:
        c.font = Font(bold=True)
    yellow = PatternFill("solid", fgColor="FFF2CC")
    for n, idx in enumerate(order, start=1):
        r = a.iloc[idx]
        code = (BUGS / r.example_file).read_text(encoding="utf-8", errors="replace").strip("\n")
        item = f"Q{n:02d}"
        key.append({"item": item, "template": r.template})
        wi.append([item, r.bug_type, CLASSES[r.bug_type][0], code, None, None, None, None, None])
        row = wi.max_row
        wi.cell(row, 4).alignment = Alignment(wrap_text=True, vertical="top")
        wi.cell(row, 4).font = Font(name="Consolas", size=9)
        for col in range(5, 10):
            wi.cell(row, col).fill = yellow
            wi.cell(row, col).alignment = Alignment(wrap_text=True, vertical="top")
        wi.row_dimensions[row].height = min(400, 13 * (code.count("\n") + 2))
    last = H + len(order)
    for col, opts in (("E", "yes,no,unsure"), ("F", "yes,limited,no,unsure"), ("G", "yes,no,unclear"),
                      ("H", "1,2,3")):
        dv = DataValidation(type="list", formula1=f'"{opts}"', allow_blank=True)
        wi.add_data_validation(dv)
        dv.add(f"{col}{H + 1}:{col}{last}")
    for col, w in zip("ABCDEFGHI", (7, 20, 26, 80, 12, 12, 12, 11, 45)):
        wi.column_dimensions[col].width = w
    wi.freeze_panes = "E5"
    wb.save(OUT / "rater_form.xlsx")
    pd.DataFrame(key).to_csv(OUT / "key.csv", index=False)
    print(f"wrote {OUT}/rater_form.xlsx ({len(order)} items) and key.csv")


if __name__ == "__main__":
    main()
